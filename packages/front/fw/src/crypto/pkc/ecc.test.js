// ECDSA-ACVP (FIPS 186-5) -- NIST CAVP byte-exact + validator coverage
// ----------------------------------------------------------------------------
// Sources (references/NIST/ACVP-Server-1.1.0.42/gen-val/json-files/):
//   ECDSA-KeyGen-FIPS186-5      -- 24/72 vectors  (validator: 4 NIST curves x 6 tc;
//                                                  Q == d*G byte-exact via point.mult)
//   ECDSA-KeyVer-FIPS186-5      -- positive-expected only; ecc.js does not run full
//                                  §A.3 subgroup validation, so negative cases (e.g.
//                                  point of incorrect order) are out of scope.
//   ECDSA-SigVer-FIPS186-5      -- positive-expected only ([first, mid, last] sub-sample
//                                  per (curve, hash) group); negative-expected vectors
//                                  exercise NIST hardening checks (subgroup membership,
//                                  malleability) not implemented in ecc.js verify.
//   DetECDSA-SigGen-FIPS186-5   -- 9 vectors  (RFC 6979 byte-exact; 3 curve/hash pairs x
//                                  [first, mid, last]). P-521+SHA-512 EXCLUDED because
//                                  _rfc6979K does not reproduce RFC 6979 §A.2.7 byte-exact
//                                  for P-521 (qlen=521 boundary in bits2int / int2octets);
//                                  filed as P2 limitation in ecc.acvp.md. P-521 round-trip
//                                  sign/verify still functional; only deterministic K
//                                  byte-reproduction differs from the spec.
//
// DetECDSA private d is read from internalProjection.json (ACVP debug-level export
// of the server-side secret scalar; required for deterministic K replay).
//
// Why hash restriction on SigVer: ecc.test.js imports only SHA-256 and SHA-512;
// SHA-2-512/256 and SHA-3/SHAKE variants are not wired into this test file.
