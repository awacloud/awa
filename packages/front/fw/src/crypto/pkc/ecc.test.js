import { describe, test, expect } from 'bun:test';
import { ecc } from './ecc.js';
import { bn } from '../utils/bn.js';
import { random } from '../utils/random.js';
import { sha256 } from '../hash/sha256.js';
import { sha384 } from '../hash/sha384.js';
import { sha512 } from '../hash/sha512.js';
import { hmac } from '../hash/hmac.js';
import { aes } from '../cipher/aes.js';
import { bitArray } from '../utils/bitArray.js';
import { utf8 } from '../../io/codec/utf8.js';
import { hex } from '../../io/codec/hex.js';

const _ba = bitArray.factory();
const _utf8 = utf8.factory();
const _hex = hex.factory();
const _aes = aes.factory();
const _sha256 = sha256.factory(_ba, _utf8);
const _rng = random.factory(_ba, _aes, _sha256);
const _bn = bn.factory(_ba, _rng);
const _sha512 = sha512.factory(_ba, _utf8);
const _sha384 = sha384.factory(_sha512);
const _hmac = hmac.factory(_ba, _utf8, _sha256);
const _ecc = ecc.factory(_ba, _hex, _bn, _sha256, _sha384, _sha512, _hmac);

describe('ecc module', () => {

    test('module metadata', () => {
        expect(ecc.name).toBe('ecc');
        expect(ecc.dependencies).toEqual(['bitArray', 'hex', 'bn', 'sha256', 'sha384', 'sha512', 'hmac']);
    });

    describe('curve registry', () => {
        test('NIST P-256 curve is registered as c256', () => {
            expect(_ecc.curves.c256).toBeDefined();
            expect(_ecc.curves.c256.G.isValid()).toBe(true);
        });

        test('curveName returns the registered short name', () => {
            expect(_ecc.curveName(_ecc.curves.c256)).toBe('c256');
        });

        test('all NIST and Koblitz generators are on their curves', () => {
            for (const k of Object.keys(_ecc.curves)) {
                expect(_ecc.curves[k].G.isValid()).toBe(true);
            }
        });
    });

    describe('point arithmetic', () => {
        test('G * 1 === G', () => {
            const G = _ecc.curves.c256.G;
            const out = G.mult(new _bn.bn(1));
            expect(out.toBits()).toEqual(G.toBits());
        });

        test('(G * 2) is on the curve', () => {
            const G = _ecc.curves.c256.G;
            expect(G.mult(new _bn.bn(2)).isValid()).toBe(true);
        });

        test('(G * a) * b === (G * b) * a', () => {
            const G = _ecc.curves.c256.G;
            const a = new _bn.bn(123456);
            const b = new _bn.bn(7891011);
            const left = G.mult(a).mult(b).toBits();
            const right = G.mult(b).mult(a).toBits();
            expect(left).toEqual(right);
        });
    });

    describe('ECDSA sign/verify', () => {
        test('round-trip on P-256', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(256);
            const msg = _sha256.hash('hello, ecdsa');
            const sig = sec.sign(msg);
            expect(pub.verify(msg, sig)).toBe(true);
        });

        test('verify fails for tampered message', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(256);
            const sig = sec.sign(_sha256.hash('original'));
            const result = pub.verify(_sha256.hash('tampered'), sig);
            expect(result).toBe(false);
        });

        test('RFC 6979 deterministic - same (msg, sk) gives identical signatures', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(256);
            const msg = _sha256.hash('rfc6979 determinism');
            const s1 = sec.sign(msg);
            const s2 = sec.sign(msg);
            expect(_ba.equal(s1, s2)).toBe(true);
            expect(pub.verify(msg, s1)).toBe(true);
        });

        test('opt-out non-deterministic mode produces distinct signatures', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(256);
            const msg = _sha256.hash('non-determinism');
            const s1 = sec.sign(msg, { deterministic: false });
            const s2 = sec.sign(msg, { deterministic: false });
            expect(_ba.equal(s1, s2)).toBe(false);
            expect(pub.verify(msg, s1)).toBe(true);
            expect(pub.verify(msg, s2)).toBe(true);
        });
    });

    describe('elGamal DH', () => {
        test('A.dh(B.pub) === B.dh(A.pub) (P-256, SHA-256)', () => {
            const a = _ecc.elGamal.generateKeys(256);
            const b = _ecc.elGamal.generateKeys(256);
            const sa = a.sec.dh(b.pub);
            const sb = b.sec.dh(a.pub);
            expect(_ba.equal(sa, sb)).toBe(true);
        });

        test('kem / unkem round-trip', () => {
            const { pub, sec } = _ecc.elGamal.generateKeys(256);
            const { key, tag } = pub.kem();
            const recovered = sec.unkem(tag);
            expect(_ba.equal(key, recovered)).toBe(true);
        });
    });

    describe('NIST CAVP ECDSA verify (FIPS 186-4 SigVer.rsp)', () => {
        // Helper: build a publicKey from raw hex Qx/Qy and verify (msg, R, S).
        function _verify(curveName, hashMod, msgHex, qxHex, qyHex, rHex, sHex) {
            const pub = _ecc.deserialize({
                type: 'ecdsa', curve: curveName,
                point: qxHex + qyHex
            });
            const msg = _hex.toBytes(msgHex);
            const h = hashMod.hash(_ba.ui8_to_ba(msg));
            const rs = _ba.ui8_to_ba(_hex.toBytes(rHex + sHex));
            return pub.verify(h, rs);
        }

        // [P-256, SHA-256] - FIPS 186-3 SigVer.rsp first valid vector
        test('P-256 / SHA-256 valid vector', () => {
            expect(_verify(
                'c256', _sha256,
                'e1130af6a38ccb412a9c8d13e15dbfc9e69a16385af3c3f1e5da954fd5e7c45f' +
                'd75e2b8c36699228e92840c0562fbf3772f07e17f1add56588dd45f7450e1217' +
                'ad239922dd9c32695dc71ff2424ca0dec1321aa47064a044b7fe3c2b97d03ce4' +
                '70a592304c5ef21eed9f93da56bb232d1eeb0035f9bf0dfafdcc4606272b20a3',
                'e424dc61d4bb3cb7ef4344a7f8957a0c5134e16f7a67c074f82e6e12f49abf3c',
                '970eed7aa2bc48651545949de1dddaf0127e5965ac85d1243d6f60e7dfaee927',
                'bf96b99aa49c705c910be33142017c642ff540c76349b9dab72f981fd9347f4f',
                '17c55095819089c2e03b9cd415abdf12444e323075d98f31920b9e0f57ec871c'
            )).toBe(true);
        });

        // Tampered S - should fail.
        test('P-256 / SHA-256 rejects tampered signature', () => {
            expect(_verify(
                'c256', _sha256,
                'e1130af6a38ccb412a9c8d13e15dbfc9e69a16385af3c3f1e5da954fd5e7c45f' +
                'd75e2b8c36699228e92840c0562fbf3772f07e17f1add56588dd45f7450e1217' +
                'ad239922dd9c32695dc71ff2424ca0dec1321aa47064a044b7fe3c2b97d03ce4' +
                '70a592304c5ef21eed9f93da56bb232d1eeb0035f9bf0dfafdcc4606272b20a3',
                'e424dc61d4bb3cb7ef4344a7f8957a0c5134e16f7a67c074f82e6e12f49abf3c',
                '970eed7aa2bc48651545949de1dddaf0127e5965ac85d1243d6f60e7dfaee927',
                'bf96b99aa49c705c910be33142017c642ff540c76349b9dab72f981fd9347f4f',
                '17c55095819089c2e03b9cd415abdf12444e323075d98f31920b9e0f57ec871d'
            )).toBe(false);
        });

        // P-384/P-521 sign/verify round-trip - confirms higher-curve path works.
        test('P-384 sign/verify round-trip', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(384);
            const msg = _sha384.hash('hello-p384');
            expect(pub.verify(msg, sec.sign(msg))).toBe(true);
        });

        test('P-521 sign/verify round-trip', () => {
            const { pub, sec } = _ecc.ecdsa.generateKeys(521);
            const msg = _sha512.hash('hello-p521');
            expect(pub.verify(msg, sec.sign(msg))).toBe(true);
        });
    });

    describe('serialize / deserialize', () => {
        test('public ECDSA key serialize → deserialize round-trip', () => {
            const { pub } = _ecc.ecdsa.generateKeys(256);
            const blob = pub.serialize();
            const restored = _ecc.deserialize(blob);
            expect(restored.getType()).toBe('ecdsa');
            expect(restored.serialize().point).toBe(blob.point);
        });

        test('secret ECDSA key serialize → deserialize round-trip', () => {
            const { sec } = _ecc.ecdsa.generateKeys(256);
            const blob = sec.serialize();
            const restored = _ecc.deserialize(blob);
            expect(restored.getType()).toBe('ecdsa');
            expect(restored.serialize().exponent).toBe(blob.exponent);
        });

        test('rejects unknown curve', () => {
            expect(_ecc.deserialize({ type: 'ecdsa', curve: 'cZZZ', point: 'aa' })).toBe(false);
        });

        test('rejects unknown type', () => {
            expect(_ecc.deserialize({ type: 'rsa', curve: 'c256', point: 'aa' })).toBe(false);
        });
    });
});


