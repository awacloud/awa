/**
 * @fileoverview A first-party sRGB ICC profile, the default destination
 * profile of a PDF/A output intent (`/DestOutputProfile`, ISO 19005-2
 * § 6.2.3, ISO 19005-4 § 6.2.3).
 *
 * `buildSrgbIcc()` assembles an ICC v2 display profile (`mntr` / `RGB ` /
 * `XYZ `) in code from the public IEC 61966-2.1 sRGB colorimetry: the sRGB
 * primaries adapted to the ICC profile connection space, its illuminant
 * as media white point and one gamma (about 2.2) curve shared by the three tone curves.
 * Colorimetric constants are facts; the profile holds no third-party ICC
 * bytes. Deterministic: the same bytes on every call. The same generator
 * as `@awacloud/facturx`'s (which pdf cannot import), its texts naming
 * `@awacloud/pdf`; provenance in `./PROVENANCE.md`.
 *
 * @module pdf/prepress/srgb-icc
 */

export const pdfSrgbIcc = {
    name: 'pdfSrgbIcc',
    dependencies: [],
    deps: [],
    factory() {
        // Keep this factory capture-free: every helper is declared in its body.
        const te = new TextEncoder();

        /** Number of colour components of the sRGB device space (the intent's `/N`). */
        const SRGB_ICC_N = 3;

        /** The output condition the sRGB profile describes. */
        const SRGB_CONDITION = 'sRGB IEC61966-2.1';

        function u32(buf, off, v) {
            buf[off] = (v >>> 24) & 0xff;
            buf[off + 1] = (v >>> 16) & 0xff;
            buf[off + 2] = (v >>> 8) & 0xff;
            buf[off + 3] = v & 0xff;
        }

        function u16(buf, off, v) {
            buf[off] = (v >>> 8) & 0xff;
            buf[off + 1] = v & 0xff;
        }

        // An ICC `s15Fixed16Number`: value × 65536, signed 32-bit big-endian.
        function s15f16(buf, off, value) {
            u32(buf, off, Math.round(value * 65536) & 0xffffffff);
        }

        function sig(buf, off, s) {
            for (let i = 0; i < 4; i++) buf[off + i] = s.charCodeAt(i);
        }

        // ICC tag data is 4-byte aligned.
        function align4(n) { return (n + 3) & ~3; }

        function writeXyz(buf, off, x, y, z) {
            sig(buf, off, 'XYZ ');
            s15f16(buf, off + 8, x);
            s15f16(buf, off + 12, y);
            s15f16(buf, off + 16, z);
        }

        /**
         * The sRGB ICC v2 display profile: header, a tag table of `desc`,
         * `wtpt`, `rXYZ` / `gXYZ` / `bXYZ`, one `curv` that `rTRC` / `gTRC`
         * / `bTRC` share, and `cprt`.
         *
         * @returns {Uint8Array}
         */
        function buildSrgbIcc() {
            // desc (textDescriptionType): sig + reserved, ASCII count, ASCII
            // with its terminator, then the empty Unicode and Mac parts.
            const descAscii = te.encode('awa sRGB (IEC 61966-2.1) ');
            const descLen = 8 + 4 + descAscii.length + 4 + 4 + 2 + 1 + 67;
            // cprt (textType): sig + reserved, ASCII with its terminator.
            const cprtAscii = te.encode('Generated by @awacloud/pdf from the public sRGB (IEC 61966-2.1) colorimetry; no third-party data. ');
            const cprtLen = 8 + cprtAscii.length;
            const xyzLen = 8 + 12;
            const curvLen = 8 + 4 + 2;

            const tags = [
                { s: 'desc', len: descLen },
                { s: 'wtpt', len: xyzLen },
                { s: 'rXYZ', len: xyzLen },
                { s: 'gXYZ', len: xyzLen },
                { s: 'bXYZ', len: xyzLen },
                { s: 'curv', len: curvLen, shared: 'trc' },
                { s: 'rTRC', shareOf: 'trc' },
                { s: 'gTRC', shareOf: 'trc' },
                { s: 'bTRC', shareOf: 'trc' },
                { s: 'cprt', len: cprtLen }
            ];

            const headerLen = 128;
            let cursor = headerLen + 4 + tags.length * 12;
            const offsets = {};
            for (const t of tags) {
                if (t.shareOf) continue;
                offsets[t.s] = { offset: cursor, len: t.len };
                if (t.shared) offsets[t.shared] = offsets[t.s];
                cursor = align4(cursor + t.len);
            }
            const buf = new Uint8Array(cursor);

            u32(buf, 0, cursor);         // profile size
            u32(buf, 8, 0x02100000);     // version 2.1.0
            sig(buf, 12, 'mntr');        // device class
            sig(buf, 16, 'RGB ');        // data colour space
            sig(buf, 20, 'XYZ ');        // PCS
            u16(buf, 24, 2026); u16(buf, 26, 1); u16(buf, 28, 1); // creation date
            sig(buf, 36, 'acsp');        // profile file signature
            u32(buf, 64, 0);             // rendering intent: perceptual
            s15f16(buf, 68, 0.9642); s15f16(buf, 72, 1.0); s15f16(buf, 76, 0.8249); // the PCS illuminant

            u32(buf, headerLen, tags.length);
            let entry = headerLen + 4;
            for (const t of tags) {
                const ref = t.shareOf ? offsets[t.shareOf] : offsets[t.s];
                sig(buf, entry, t.s);
                u32(buf, entry + 4, ref.offset);
                u32(buf, entry + 8, ref.len);
                entry += 12;
            }

            const desc = offsets.desc.offset;
            sig(buf, desc, 'desc');
            u32(buf, desc + 8, descAscii.length);
            buf.set(descAscii, desc + 12);
            writeXyz(buf, offsets.wtpt.offset, 0.9642, 1.0, 0.8249);
            // The sRGB colorants adapted to the PCS illuminant.
            writeXyz(buf, offsets.rXYZ.offset, 0.43607, 0.22249, 0.01392);
            writeXyz(buf, offsets.gXYZ.offset, 0.38515, 0.71687, 0.09708);
            writeXyz(buf, offsets.bXYZ.offset, 0.14307, 0.06061, 0.71410);
            const trc = offsets.trc.offset;
            sig(buf, trc, 'curv');
            u32(buf, trc + 8, 1);        // one entry: a gamma value follows
            u16(buf, trc + 12, 0x0233);  // u8Fixed8 ≈ 2.2
            const cprt = offsets.cprt.offset;
            sig(buf, cprt, 'text');
            buf.set(cprtAscii, cprt + 8);
            return buf;
        }

        return { buildSrgbIcc, SRGB_ICC_N, SRGB_CONDITION };
    }
};
