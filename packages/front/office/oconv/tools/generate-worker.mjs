/**
 * @fileoverview `bun run gen:worker` — build `src/worker.js`, the
 * self-contained oconv worker (office-coverage-3 T65, D40).
 *
 * `src/worker/entry.js` (the worker's source: it imports `@awacloud/*`
 * bare specifiers) is bundled by `Bun.build` (browser, ESM; not minified:
 * the identifiers stay readable, and the publication scans read it as
 * source) into one file that imports nothing, so a static page can start it with
 * `new Worker('/vendor/oconv/worker.js', { type: 'module' })`: a module
 * worker has no import map. The licence header and a "generated" line
 * open the file. `buildWorker()` returns the text; run as a script it
 * writes `src/worker.js`, or with `--check` exits 1 when the committed
 * file differs from a fresh build.
 *
 * @module oconv/tools/generate-worker
 */

/* global Bun */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = join(PKG, 'src', 'worker', 'entry.js');
export const OUT = join(PKG, 'src', 'worker.js');

// The entry's own four licence lines, then the generated line.
const HEADER = [
    ...readFileSync(ENTRY, 'utf8').split('\n').slice(0, 4),
    '// Generated by `bun run gen:worker` (tools/generate-worker.mjs) — do not edit; source src/worker/entry.js.',
    ''
].join('\n');

/** The bundled worker's text: the header, then the minified bundle of the entry. */
export async function buildWorker() {
    // Bun writes each module's `// <path>` comment relative to the working
    // directory (its `root` option does not change them): build from the
    // package, as `bun run gen:worker` does, so the bundle is the same
    // wherever the caller (a test run from the repo root) started.
    const cwd = process.cwd();
    process.chdir(PKG);
    let result;
    try {
        result = await Bun.build({ entrypoints: [ENTRY], target: 'browser', format: 'esm' });
    } finally {
        process.chdir(cwd);
    }
    if (!result.success || result.outputs.length !== 1)
        throw new Error(`generate-worker: the build failed:\n${result.logs.map((l) => l.message).join('\n')}`);
    return HEADER + await result.outputs[0].text();
}

if (import.meta.main) {
    const text = await buildWorker();
    if (process.argv.includes('--check')) {
        const same = readFileSync(OUT, 'utf8') === text;
        process.stdout.write(`generate-worker: src/worker.js is ${same ? 'up to date' : 'STALE'}\n`);
        process.exit(same ? 0 : 1);
    }
    writeFileSync(OUT, text);
    process.stdout.write(`generate-worker: wrote src/worker.js (${text.length} bytes)\n`);
}
