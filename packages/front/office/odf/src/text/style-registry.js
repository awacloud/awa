/**
 * @fileoverview Deterministic automatic-style registry (write side) and
 * style resolver (read side) for the emphasis / list-numbering seam of
 * `content.xml`, extended with the body-table grid seam (bordered cells,
 * margins-aligned tables).
 *
 * Two halves, one frozen contract:
 *
 * - **Write** — `createRegistry(reserved?)` hands out deterministic
 *   `awa-t-*` / `awa-l-*` / `awa-c-*` / `awa-tb-*` automatic-style names
 *   for a set of semantic flags, then materialises them as a `styleAutomatic` model
 *   (`toAutomaticStyles()`) plus an `office:font-face-decls` element
 *   (`toFontFaceDecls()`) when a monospace face is needed.
 * - **Read** — `createResolver(contentAutoStyles, fontFaces, namedStyles)`
 *   answers `textFlags(name)` / `listNumbering(name)` /
 *   `cellBorders(name)` / `tableAlign(name)` for a style name
 *   referenced by a body element, and records which **content automatic**
 *   styles were resolved (`consumed`) so the orchestrator can drop them
 *   from the surfaced passthrough model.
 *
 * **Honesty rule** — the resolver resolves only a *fully mapped* style:
 * every attribute of the style is one this module can prove the meaning
 * of. Anything else stays `null`, so the caller keeps the opaque
 * `styleName` passthrough instead of guessing.
 *
 * This module is import-free by design (`dependencies` only); the
 * `deps:` field and descriptor imports are generated by
 * `bun cli.ts fw-codegen deps`.
 *
 * @module odf/text/styleRegistry
 */

import { xml } from '@awacloud/fw/io/codec/xml.js';

export const textStyleRegistry = {
    name: 'textStyleRegistry',
    dependencies: ['xml'],
    deps: [xml],

    factory(xml) {

        // -----------------------------------------------------------------
        // Frozen ctx contract — tasks building on this module rely on the
        // signatures below verbatim.
        //
        //   createRegistry(reserved?: {styles?: Set<string>,
        //                              fontFaces?: Set<string>}) → registry
        //     registry.textStyle({bold?, italic?, strike?, monospace?}) → string
        //     registry.listStyle({ordered: boolean,
        //                         numFormat?: '1'|'a'|'A'|'i'|'I'}) → string
        //     registry.cellStyle({bordered: true}) → string     // 'awa-c-b'
        //     registry.tableStyle({align: 'margins'}) → string  // 'awa-tb-m'
        //     registry.toAutomaticStyles() → {styles:[…], _extras?:{children:[…]}} | null
        //     registry.toFontFaceDecls()  → rawElement | null
        //
        //   createResolver(contentAutoStyles, fontFaces, namedStyles) → resolver
        //     resolver.textFlags(styleName)
        //       → {bold?, italic?, strike?, monospace?, source:'auto'|'named'} | null
        //     resolver.listNumbering(styleName)
        //       → {ordered: boolean, numFormat?: string, source:'auto'|'named'} | null
        //     resolver.cellBorders(styleName)
        //       → {bordered: true, source:'auto'|'named'} | null
        //     resolver.tableAlign(styleName)
        //       → {align: 'margins', source:'auto'|'named'} | null
        //     resolver.consumed → Set<string>   // 'auto'-source resolutions ONLY
        // -----------------------------------------------------------------

        /**
         * Mirror of `styleAutomatic`'s `PROP_TAGS` — this factory is
         * capture-free and declares only `xml`, so the shared pure mapping
         * is duplicated here rather than imported (`fw/no-factory-capture`).
         * A drift test pins it against the live `styleAutomatic` module.
         */
        const PROP_TAGS = {
            'style:paragraph-properties':    'paragraph',
            'style:text-properties':         'text',
            'style:table-properties':        'table',
            'style:table-column-properties': 'tableColumn',
            'style:table-row-properties':    'tableRow',
            'style:table-cell-properties':   'tableCell',
            'style:graphic-properties':      'graphic'
        };

        /** Metadata-only attributes tolerated on a named (`office:styles`) style. */
        const TOLERATED_NAMED_ATTRS = new Set(['style:display-name', 'style:class']);

        const MONO_FACE_BASE = 'awa-mono';

        /**
         * Label-alignment indent (`fo:margin-left` and the list tab stop)
         * of list levels 1..10 — declared literally, never computed, so
         * the emitted strings carry no runtime float formatting.
         */
        const LIST_LEVEL_MARGINS = [
            '1.27cm', '1.905cm', '2.54cm', '3.175cm', '3.81cm',
            '4.445cm', '5.08cm', '5.715cm', '6.35cm', '6.985cm'
        ];
        const LIST_LABEL_INDENT = '-0.635cm';

        /** Grid-seam property bags (bordered table cell, margins table). */
        const CELL_BORDER = '0.5pt solid #000000';
        const CELL_PADDING = '0.097cm';
        const CELL_KEYS = new Set(['fo:border', 'fo:padding']);
        const FLAG_ORDER = [
            ['bold', 'b'],
            ['italic', 'i'],
            ['strike', 's'],
            ['monospace', 'm']
        ];

        function toSet(v) {
            if (!v) return new Set();
            if (v instanceof Set) return v;
            return new Set(v);
        }

        // =================================================================
        // Write side
        // =================================================================

        /**
         * Create a write-side automatic-style registry.
         *
         * @param {{styles?: Set<string>, fontFaces?: Set<string>}} [reserved]
         *   names already used by passthrough material that must not be
         *   shadowed — a collision is resolved with the first free
         *   `-2`, `-3`, … suffix.
         * @returns {object} `{ textStyle, listStyle, cellStyle, tableStyle,
         *   toAutomaticStyles, toFontFaceDecls }`
         */
        function createRegistry(reserved) {
            const reservedStyles = toSet(reserved && reserved.styles);
            const reservedFaces = toSet(reserved && reserved.fontFaces);

            const textByKey = new Map();   // 'bism' subset  → allocated name
            const listByKey = new Map();   // 'b' | 'n<fmt>' → { name, ordered, numFormat }
            const used = new Set();        // names this registry handed out
            let cellName = null;           // 'awa-c-b' once requested
            let tableName = null;          // 'awa-tb-m' once requested
            let monoFace = null;

            function alloc(base) {
                if (!reservedStyles.has(base) && !used.has(base)) {
                    used.add(base);
                    return base;
                }
                let i = 2;
                while (reservedStyles.has(`${base}-${i}`) || used.has(`${base}-${i}`)) i++;
                const name = `${base}-${i}`;
                used.add(name);
                return name;
            }

            function ensureMonoFace() {
                if (monoFace) return monoFace;
                let name = MONO_FACE_BASE;
                if (reservedFaces.has(name)) {
                    let i = 2;
                    while (reservedFaces.has(`${MONO_FACE_BASE}-${i}`)) i++;
                    name = `${MONO_FACE_BASE}-${i}`;
                }
                monoFace = name;
                return name;
            }

            /**
             * Name of the `text`-family automatic style carrying the given
             * emphasis flags. Deterministic (`awa-t-` + `b`,`i`,`s`,`m` in
             * that fixed order) and deduplicated — the same combination
             * always yields the same name. Callers guarantee ≥1 flag.
             *
             * @param {{bold?: boolean, italic?: boolean, strike?: boolean,
             *          monospace?: boolean}} flags
             * @returns {string}
             */
            function textStyle(flags) {
                const f = flags || {};
                let key = '';
                for (const [prop, letter] of FLAG_ORDER) if (f[prop]) key += letter;
                const seen = textByKey.get(key);
                if (seen) {
                    if (f.monospace) ensureMonoFace();
                    return seen;
                }
                const name = alloc(`awa-t-${key}`);
                textByKey.set(key, name);
                if (f.monospace) ensureMonoFace();
                return name;
            }

            /**
             * Name of the `text:list-style` carrying the given numbering.
             *
             * @param {{ordered: boolean, numFormat?: string}} spec
             * @returns {string}
             */
            function listStyle(spec) {
                const ordered = !!(spec && spec.ordered);
                const numFormat = ordered ? ((spec && spec.numFormat) || '1') : null;
                const key = ordered ? `n${numFormat}` : 'b';
                const seen = listByKey.get(key);
                if (seen) return seen.name;
                const name = alloc(`awa-l-${key}`);
                listByKey.set(key, { name, ordered, numFormat });
                return name;
            }

            /**
             * Name of the `table-cell`-family automatic style drawing a
             * bordered grid cell. `{bordered: true}` is the only spec
             * today; deterministic (`awa-c-b`) and deduplicated, with the
             * same collision-suffix rule as every other registry name.
             *
             * @param {{bordered: true}} spec
             * @returns {string}
             */
            function cellStyle(spec) {
                void spec;
                if (!cellName) cellName = alloc('awa-c-b');
                return cellName;
            }

            /**
             * Name of the `table`-family automatic style aligning a table
             * to the page margins. `{align: 'margins'}` is the only spec
             * today; deterministic (`awa-tb-m`) and deduplicated.
             *
             * @param {{align: 'margins'}} spec
             * @returns {string}
             */
            function tableStyle(spec) {
                void spec;
                if (!tableName) tableName = alloc('awa-tb-m');
                return tableName;
            }

            /**
             * The label-alignment `style:list-level-properties` child every
             * generated list level carries (level is 1-based).
             */
            function levelPropsEl(level) {
                const ml = LIST_LEVEL_MARGINS[level - 1];
                return xml.el('style:list-level-properties', {
                    'text:list-level-position-and-space-mode': 'label-alignment'
                }, [
                    xml.el('style:list-level-label-alignment', {
                        'text:label-followed-by': 'listtab',
                        'text:list-tab-stop-position': ml,
                        'fo:text-indent': LIST_LABEL_INDENT,
                        'fo:margin-left': ml
                    }, [])
                ]);
            }

            function listStyleEl(entry) {
                const levels = [];
                for (let level = 1; level <= 10; level++) {
                    levels.push(entry.ordered
                        ? xml.el('text:list-level-style-number', {
                            'text:level': String(level),
                            'style:num-format': entry.numFormat,
                            'style:num-suffix': '.'
                        }, [levelPropsEl(level)])
                        : xml.el('text:list-level-style-bullet', {
                            'text:level': String(level),
                            'text:bullet-char': '•'
                        }, [levelPropsEl(level)]));
                }
                return xml.el('text:list-style', { 'style:name': entry.name }, levels);
            }

            /**
             * Materialise everything requested so far as a `styleAutomatic`
             * model. Emphasis combinations become typed `style:style`
             * entries, followed by the grid-seam cell (`awa-c-b`) and table
             * (`awa-tb-m`) styles when requested; list styles are raw
             * elements in `_extras.children`
             * (`styleAutomatic.render` appends those verbatim).
             *
             * @returns {object|null} `null` when nothing was requested.
             */
            function toAutomaticStyles() {
                if (!textByKey.size && !listByKey.size && !cellName && !tableName) return null;
                const styles = [];
                for (const [key, name] of textByKey) {
                    const bag = {};
                    if (key.includes('b')) bag['fo:font-weight'] = 'bold';
                    if (key.includes('i')) bag['fo:font-style'] = 'italic';
                    if (key.includes('s')) bag['style:text-line-through-style'] = 'solid';
                    if (key.includes('m')) bag['style:font-name'] = monoFace;
                    styles.push({ name, family: 'text', properties: { text: bag } });
                }
                if (cellName) {
                    styles.push({ name: cellName, family: 'table-cell', properties: {
                        tableCell: { 'fo:border': CELL_BORDER, 'fo:padding': CELL_PADDING }
                    } });
                }
                if (tableName) {
                    styles.push({ name: tableName, family: 'table', properties: {
                        table: { 'table:align': 'margins' }
                    } });
                }
                const model = { styles };
                if (listByKey.size) {
                    const children = [];
                    for (const entry of listByKey.values()) children.push(listStyleEl(entry));
                    model._extras = { children };
                }
                return model;
            }

            /**
             * The `office:font-face-decls` element required by the emitted
             * styles — present iff at least one monospace text style was
             * requested.
             *
             * @returns {object|null}
             */
            function toFontFaceDecls() {
                if (!monoFace) return null;
                return xml.el('office:font-face-decls', {}, [
                    xml.el('style:font-face', {
                        'style:name': monoFace,
                        'svg:font-family': 'monospace',
                        'style:font-family-generic': 'modern',
                        'style:font-pitch': 'fixed'
                    }, [])
                ]);
            }

            return { textStyle, listStyle, cellStyle, tableStyle,
                     toAutomaticStyles, toFontFaceDecls };
        }

        // =================================================================
        // Read side
        // =================================================================

        /**
         * Type a raw `style:style` element the way `styleAutomatic.parseStyle`
         * does. Mirrored here because this factory declares only `xml`
         * (`fw/no-factory-capture`); a drift test pins the two against each
         * other.
         *
         * @param {object} el
         * @returns {object}
         */
        function typeRawStyle(el) {
            const a = (el && el.attrs) || {};
            const out = {
                name: a['style:name'] || '',
                family: a['style:family'] || '',
                properties: {}
            };
            if (a['style:parent-style-name']) out.parentStyleName = a['style:parent-style-name'];
            const known = new Set(['style:name', 'style:family', 'style:parent-style-name']);
            const extraAttrs = {};
            let anyAttr = false;
            for (const k of Object.keys(a)) {
                if (!known.has(k)) { extraAttrs[k] = a[k]; anyAttr = true; }
            }
            const extraChildren = [];
            for (const c of (el && el.children) || []) {
                if (c.type !== 'element') continue;
                const key = PROP_TAGS[c.name];
                if (key) out.properties[key] = { ...(c.attrs || {}) };
                else extraChildren.push(c);
            }
            if (anyAttr || extraChildren.length) {
                out._extras = {};
                if (anyAttr) out._extras.attrs = extraAttrs;
                if (extraChildren.length) out._extras.children = extraChildren;
            }
            return out;
        }

        /**
         * Create a read-side resolver over the three style sources of an
         * `.odt`.
         *
         * @param {object|null} contentAutoStyles — `styleAutomatic` model of
         *   `content.xml`'s `<office:automatic-styles>`.
         * @param {Array<object>} fontFaces — raw `style:font-face` elements,
         *   the union of `content.xml`'s and `styles.xml`'s declarations.
         * @param {Array<object>|null} namedStyles — raw elements of the
         *   `styles.xml` `<office:styles>` bucket. `styles.xml`'s own
         *   automatic-styles bucket is excluded by design.
         * @returns {object} `{ textFlags, listNumbering, cellBorders,
         *   tableAlign, consumed }`
         */
        function createResolver(contentAutoStyles, fontFaces, namedStyles) {
            const consumed = new Set();
            const autoStyleByName = new Map();
            const autoListByName = new Map();
            const namedStyleByName = new Map();   // name → array of raw elements
            const namedListByName = new Map();    // name → array of raw elements
            const faceByName = new Map();

            for (const s of (contentAutoStyles && contentAutoStyles.styles) || []) {
                if (s && s.name) autoStyleByName.set(s.name, s);
            }
            for (const c of (contentAutoStyles && contentAutoStyles._extras
                             && contentAutoStyles._extras.children) || []) {
                if (c && c.type === 'element' && c.name === 'text:list-style') {
                    const n = c.attrs && c.attrs['style:name'];
                    if (n) autoListByName.set(n, c);
                }
            }
            for (const f of fontFaces || []) {
                const n = f && f.attrs && f.attrs['style:name'];
                if (n && !faceByName.has(n)) faceByName.set(n, f);
            }
            for (const el of namedStyles || []) {
                if (!el || el.type !== 'element') continue;
                const n = el.attrs && el.attrs['style:name'];
                if (!n) continue;
                const bucket = el.name === 'style:style' ? namedStyleByName
                    : el.name === 'text:list-style' ? namedListByName
                        : null;
                if (!bucket) continue;
                if (!bucket.has(n)) bucket.set(n, []);
                bucket.get(n).push(el);
            }

            /** A face is monospace-declared by either marker
             * (`style:font-pitch="fixed"` or `style:font-family-generic="modern"`). */
            function isMonoFace(faceName) {
                const el = faceByName.get(faceName);
                if (!el) return false;
                const a = el.attrs || {};
                return a['style:font-pitch'] === 'fixed'
                    || a['style:font-family-generic'] === 'modern';
            }

            /**
             * Map a `style:text-properties` attribute bag to semantic flags,
             * or `null` when any key/value is not provably one of the four.
             */
            function flagsFromBag(bag) {
                const out = {};
                for (const k of Object.keys(bag)) {
                    const v = bag[k];
                    if (k === 'fo:font-weight') {
                        if (v !== 'bold') return null;
                        out.bold = true;
                    } else if (k === 'fo:font-style') {
                        if (v !== 'italic') return null;
                        out.italic = true;
                    } else if (k === 'style:text-line-through-style') {
                        if (!v || v === 'none') return null;
                        out.strike = true;
                    } else if (k === 'style:font-name') {
                        if (!isMonoFace(v)) return null;
                        out.monospace = true;
                    } else {
                        return null;
                    }
                }
                return Object.keys(out).length ? out : null;
            }

            /**
             * Apply the fully-mapped rule to a typed style.
             *
             * @param {object} s typed style
             * @param {Set<string>|null} tolerated extra attributes to ignore
             */
            function mapTypedStyle(s, tolerated) {
                const bag = soleBag(s, 'text', 'text', tolerated);
                return bag ? flagsFromBag(bag) : null;
            }

            /**
             * Structural half of the fully-mapped rule shared by every
             * typed style mapping: the given family, no parent chain, ONE
             * properties bag under `propKey`, no extra child, no extra
             * attribute beyond `tolerated`. Returns that bag or `null`.
             */
            function soleBag(s, family, propKey, tolerated) {
                if (!s || s.family !== family) return null;
                if (s.parentStyleName) return null;
                const props = s.properties || {};
                const keys = Object.keys(props);
                if (keys.length !== 1 || keys[0] !== propKey) return null;
                if (s._extras) {
                    if (s._extras.children && s._extras.children.length) return null;
                    const xa = s._extras.attrs || {};
                    for (const k of Object.keys(xa)) {
                        if (!tolerated || !tolerated.has(k)) return null;
                    }
                }
                return props[propKey] || {};
            }

            /** `{bordered:true}` iff the cell bag is a pure, visible border. */
            function mapCellStyle(s, tolerated) {
                const bag = soleBag(s, 'table-cell', 'tableCell', tolerated);
                if (!bag) return null;
                for (const k of Object.keys(bag)) if (!CELL_KEYS.has(k)) return null;
                const border = bag['fo:border'];
                if (!border || border === 'none') return null;
                return { bordered: true };
            }

            /** `{align:'margins'}` iff the table bag is exactly that. */
            function mapTableStyle(s, tolerated) {
                const bag = soleBag(s, 'table', 'table', tolerated);
                if (!bag) return null;
                const keys = Object.keys(bag);
                if (keys.length !== 1 || bag['table:align'] !== 'margins') return null;
                return { align: 'margins' };
            }

            /**
             * Resolve a `style:style` reference through a typed mapping:
             * content automatic styles first (consumed on success), then
             * the named `office:styles` entries (kept, never consumed).
             */
            function resolveStyle(styleName, map) {
                if (!styleName) return null;
                const auto = autoStyleByName.get(styleName);
                if (auto) {
                    const got = map(auto, null);
                    if (got) {
                        consumed.add(styleName);
                        return { ...got, source: 'auto' };
                    }
                }
                for (const el of namedStyleByName.get(styleName) || []) {
                    const got = map(typeRawStyle(el), TOLERATED_NAMED_ATTRS);
                    if (got) return { ...got, source: 'named' };
                }
                return null;
            }

            /**
             * Semantic emphasis flags behind a `text:style-name` reference.
             *
             * @param {string} styleName
             * @returns {object|null}
             */
            function textFlags(styleName) {
                return resolveStyle(styleName, mapTypedStyle);
            }

            /**
             * Bordered-cell semantics behind a cell's `table:style-name`:
             * family `table-cell`, no parent, a `tableCell` bag whose keys
             * are a subset of `fo:border`/`fo:padding` with a visible
             * `fo:border` (neither empty nor `none`).
             *
             * @param {string} styleName
             * @returns {{bordered: true, source: string}|null}
             */
            function cellBorders(styleName) {
                return resolveStyle(styleName, mapCellStyle);
            }

            /**
             * Margins alignment behind a table's `table:style-name`:
             * family `table`, no parent, a `table` bag of exactly
             * `{'table:align': 'margins'}`.
             *
             * @param {string} styleName
             * @returns {{align: 'margins', source: string}|null}
             */
            function tableAlign(styleName) {
                return resolveStyle(styleName, mapTableStyle);
            }

            /** First element child decides the numbering; anything else → `null`. */
            function mapListEl(el) {
                for (const c of (el && el.children) || []) {
                    if (c.type !== 'element') continue;
                    if (c.name === 'text:list-level-style-number') {
                        const fmt = (c.attrs && c.attrs['style:num-format']) || '1';
                        return { ordered: true, numFormat: fmt };
                    }
                    if (c.name === 'text:list-level-style-bullet') return { ordered: false };
                    return null;
                }
                return null;
            }

            /**
             * Numbering behind a `text:style-name` reference on a list.
             *
             * @param {string} styleName
             * @returns {object|null}
             */
            function listNumbering(styleName) {
                if (!styleName) return null;
                const auto = autoListByName.get(styleName);
                if (auto) {
                    const num = mapListEl(auto);
                    if (num) {
                        consumed.add(styleName);
                        return { ...num, source: 'auto' };
                    }
                }
                for (const el of namedListByName.get(styleName) || []) {
                    const num = mapListEl(el);
                    if (num) return { ...num, source: 'named' };
                }
                return null;
            }

            return {
                textFlags,
                listNumbering,
                cellBorders,
                tableAlign,
                get consumed() { return consumed; }
            };
        }

        return { createRegistry, createResolver };
    }
};
